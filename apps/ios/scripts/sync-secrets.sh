#!/bin/sh
# Writes Config/Secrets.xcconfig from the web app's apps/web/.env.local so the
# iOS app talks to the same Supabase project. Safe to re-run.
set -eu
here=$(cd "$(dirname "$0")/.." && pwd)
env_file="$here/../web/.env.local"
out="$here/Config/Secrets.xcconfig"

if [ ! -f "$env_file" ]; then
  echo "No $env_file — fill in Config/Secrets.example.xcconfig by hand instead." >&2
  exit 1
fi

value() { grep -E "^$1=" "$env_file" | tail -n 1 | cut -d= -f2- | tr -d '"'"'"' \r'; }
url=$(value NEXT_PUBLIC_SUPABASE_URL)
key=$(value NEXT_PUBLIC_SUPABASE_ANON_KEY)
if [ -z "$url" ] || [ -z "$key" ]; then
  echo "NEXT_PUBLIC_SUPABASE_URL / NEXT_PUBLIC_SUPABASE_ANON_KEY missing from $env_file" >&2
  exit 1
fi

host=${url#https://}
host=${host#http://}
host=${host%/}
{
  echo "// Generated by scripts/sync-secrets.sh from apps/web/.env.local. Not committed."
  echo "SUPABASE_HOST = $host"
  echo "SUPABASE_ANON_KEY = $key"
} > "$out"
echo "Wrote $out (host: $host)"
